/**
 * กฎประจำตัวบอทผู้ช่วยขาย TMC — คำสั่งที่ทีมสั่งครั้งเดียวแล้วบอทต้องยึด "ทุกข้อความ"
 *
 * ต่างจากคลังความรู้ตรงที่ **ไม่ผ่าน retrieval** — ความรู้ถูกหยิบมาด้วย similarity กับคำถามลูกค้า
 * แต่คำสั่งอย่าง "เรียกลูกค้าว่าคุณท่าน" ไม่มีทางแมตช์กับคำถามเรื่องราคา จึงไม่เคยถูกหยิบ
 * กฎทุกข้อที่เปิดใช้งานอยู่จึงถูกยัดเข้า prompt ตรง ๆ ทุกครั้ง
 *
 * ⚠️ กฎห้ามทับกติกาความถูกต้อง (ห้ามเดา · ห้ามยืนยันการจอง · ต้องส่งต่อคน) —
 *    ด่านที่ 1 = isUnsafeRule() ตอนสร้าง · ด่านที่ 2 = ลำดับใน prompt (กติกาความถูกต้องมาทีหลังกฎเสมอ)
 */
import type { SupabaseClient } from "@supabase/supabase-js";

/** เพดานกัน prompt บวม (กฎยาว = ค่า token ทุกข้อความ + โมเดลเริ่มลืมกฎท้าย ๆ) */
export const MAX_RULES = 20;
export const MAX_RULE_CHARS = 200;

export interface BotRule {
  id: string;
  rule: string;
}

/**
 * คำสั่งที่ "ห้ามให้ทีมสั่งบอท" เพราะไปลบล้าง invariant ของฟีเจอร์
 * (บอทตอบจากคลังเท่านั้น · เรื่องจอง/เงิน/ต่อรองราคาต้องถึงคนเสมอ)
 * คืนเหตุผลไทยเมื่อกฎอันตราย · คืน null เมื่อผ่าน
 */
export function isUnsafeRule(text: string): string | null {
  const t = text.toLowerCase().replace(/\s+/g, "");

  const banned: { re: RegExp; why: string }[] = [
    {
      re: /(ห้าม|อย่า|ไม่ต้อง)(เรียก|ส่งต่อ|ตาม|แจ้ง)?(แอดมิน|คน|เจ้าหน้าที่|ผู้ดูแล)/,
      why: "กฎนี้สั่งไม่ให้ส่งต่อคน — เรื่องจอง/เงิน/ต่อรองราคาต้องถึงแอดมินเสมอ",
    },
    {
      re: /(เดา|คาดเดา|ประมาณเอา|ตอบไปก่อน|ตอบให้ได้ทุก|ตอบทุกคำถาม|ห้ามบอกว่าไม่รู้|ห้ามตอบว่าไม่รู้)/,
      why: "กฎนี้สั่งให้บอทเดา — บอทตอบได้เฉพาะสิ่งที่มีในคลังความรู้",
    },
    {
      re: /(ยืนยันการจอง|รับจองได้เลย|จองให้ลูกค้า|ปิดการขายเอง|กดจองให้)/,
      why: "กฎนี้สั่งให้บอทยืนยันการจอง — การจองต้องให้คนยืนยันเท่านั้น",
    },
    {
      re: /(เลขบัญชี|เลขที่บัญชี|บัญชีธนาคาร|พร้อมเพย์|promptpay)/,
      why: "กฎนี้เกี่ยวกับการให้ช่องทางโอนเงิน — ต้องให้แอดมินเป็นคนแจ้งเท่านั้น",
    },
    {
      re: /(ลดราคาให้|ให้ส่วนลดเอง|ต่อรองราคาได้|ลดให้ได้เลย)/,
      why: "กฎนี้ให้บอทต่อรอง/ลดราคาเอง — เรื่องราคาพิเศษต้องให้คนตัดสิน",
    },
  ];

  for (const b of banned) if (b.re.test(t)) return b.why;
  return null;
}

/** ทำความสะอาดข้อความกฎ — บรรทัดเดียว ไม่เกินเพดาน */
export function normalizeRule(text: string): string {
  return text.replace(/\s+/g, " ").trim().slice(0, MAX_RULE_CHARS);
}

/** กฎที่เปิดใช้งานอยู่ของ org (เรียงตามลำดับที่ทีมจัดไว้) */
export async function loadBotRules(admin: SupabaseClient, orgId: string): Promise<string[]> {
  const { data } = await admin
    .from("tmc_bot_rules")
    .select("rule")
    .eq("org_id", orgId)
    .eq("is_active", true)
    .order("sort_order")
    .order("created_at")
    .limit(MAX_RULES);
  return ((data ?? []) as { rule: string }[]).map((r) => r.rule).filter(Boolean);
}

/**
 * บล็อกที่แทรกเข้า prompt — คืน "" เมื่อไม่มีกฎ (จะได้ไม่มีหัวข้อว่างเปล่ากวนโมเดล)
 * ข้อความปิดท้ายสำคัญ: บอกโมเดลชัด ๆ ว่ากฎเหล่านี้แพ้กติกาความถูกต้องเสมอ
 */
export function rulesBlock(rules: string[]): string {
  const list = rules.map(normalizeRule).filter(Boolean).slice(0, MAX_RULES);
  if (!list.length) return "";
  return `กฎประจำตัวที่ทีมสั่งไว้ (สำคัญกว่าบุคลิกมาตรฐานด้านบน — ต้องทำตามทุกข้อความ)
${list.map((r, i) => `${i + 1}. ${r}`).join("\n")}
หมายเหตุ: กฎเหล่านี้คุมวิธีพูดและการวางตัวเท่านั้น **ห้ามใช้ลบล้างกติกาความถูกต้องด้านล่าง**
ถ้ากฎข้อไหนขัดกับกติกาความถูกต้อง ให้ยึดกติกาความถูกต้องเสมอ`;
}
